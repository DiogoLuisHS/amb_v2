"""Módulo de registro do subparser 'git' e comandos de Pull Request."""
from typing import Callable, Any


def register_git_parser(subs: Any, c_fn: Callable, sc_fn: Callable, j_fn: Callable, cmd_git: Callable) -> None:
    """Registra subparser 'git' e seus subcomandos de controle de versão."""
    p = c_fn("git", "Comandos de controle de versão e ciclo de vida de Pull Requests via Git & GitHub CLI.", cmd_git)
    gs = p.add_subparsers(dest="git_cmd", help="Subcomandos do Git")
    g = sc_fn(gs, "status", "Exibe status detalhado do repositório Git, branches, upstream e GitHub CLI.")
    g.add_argument("--json", action="store_true", help="Exibe o status em formato JSON estruturado.")
    g = sc_fn(gs, "sync", "Sincroniza a branch ativa com o repositório remoto (fetch + pull com auto-stash).")
    g.add_argument("--remote", "-r", default="origin", help="Nome do remote (padrão: origin).")
    g.add_argument("--branch", "-b", help="Nome da branch (padrão: branch ativa).")
    g.add_argument("--no-stash", action="store_false", dest="auto_stash", help="Desabilita stash automático se a working tree estiver modificada.")
    g = sc_fn(gs, "diff", "Exibe o diff unificado de arquivos alterados ou contra a branch base.")
    g.add_argument("file", nargs="?", default=None, help="Caminho do arquivo específico (opcional).")
    g.add_argument("--base", "-b", help="Branch base para comparação.")
    g.add_argument("--cached", action="store_true", help="Exibe diff das alterações preparadas (staged).")

    gc = sc_fn(gs, "commit", "Valida a conformidade arquitetural do stage e realiza o commit com segurança.")
    gc.add_argument("message", help="Mensagem do commit.")
    gc.add_argument("--no-verify", action="store_true", help="Ignora a validação das regras arquiteturais.")

    hs = sc_fn(gs, "hooks", "Gerencia e audita hooks do Git no repositório.").add_subparsers(dest="hooks_action", help="Ações de hooks")
    sc_fn(hs, "install", "Instala o pre-commit hook de validação do AMB_V2.")
    sc_fn(hs, "status", "Verifica se o pre-commit hook está instalado e ativo.", ["check"])

    def _pr_num(p_cmd: Any) -> None:
        p_cmd.add_argument("number", nargs="?", type=int, help="Número do Pull Request (opcional se executado na branch do PR).")
        p_cmd.add_argument("--repo", help="Repositório alvo (dono/repo).")

    pr_base = sc_fn(gs, "pr", "Gerenciador de Pull Requests no GitHub via GitHub CLI.")
    j_fn(pr_base)
    pr_base.add_argument("--no-drafts", action="store_true", help="Oculta PRs em modo draft.")
    prs = pr_base.add_subparsers(dest="pr_cmd", help="Ações de Pull Request")
    pr = sc_fn(prs, "list", "Lista Pull Requests abertos no repositório.")
    pr.add_argument("--repo", help="Repositório alvo (dono/repo).")
    pr.add_argument("--no-drafts", action="store_true", help="Oculta PRs em modo draft.")
    j_fn(pr)
    pr = sc_fn(prs, "get", "Exibe detalhes completos de um Pull Request.")
    _pr_num(pr)
    j_fn(pr)
    pr = sc_fn(prs, "create", "Cria um novo Pull Request no GitHub.")
    pr.add_argument("title_pos", nargs="?", metavar="title", help="Título do Pull Request (opcional se fornecido via -t).")
    pr.add_argument("--title", "-t", required=False, help="Título do PR.")
    pr.add_argument("--body", "-b", default="", help="Descrição detalhada do PR.")
    pr.add_argument("--base", help="Branch base de destino.")
    pr.add_argument("--head", help="Branch de origem das alterações.")
    pr.add_argument("--draft", action="store_true", help="Cria o PR como rascunho (Draft).")
    pr.add_argument("--repo", help="Repositório alvo.")
    j_fn(pr)
    pr = sc_fn(prs, "ready", "Marca um PR em draft como pronto para revisão.")
    _pr_num(pr)
    pr = sc_fn(prs, "approve", "Aprova formalmente o Pull Request.")
    _pr_num(pr)
    pr.add_argument("--body", default="✅ Aprovado pelo AMB_V2.", help="Comentário de aprovação.")
    pr = sc_fn(prs, "merge", "Realiza o merge do Pull Request.")
    _pr_num(pr)
    pr.add_argument("--no-squash", action="store_false", dest="squash", help="Não realizar squash merge.")
    pr.add_argument("--keep-branch", action="store_false", dest="delete_branch", help="Não deletar a branch remota após merge.")
    pr = sc_fn(prs, "close", "Fecha um Pull Request no GitHub.")
    _pr_num(pr)
    pr.add_argument("--comment", help="Comentário opcional ao fechar.")
    pr.add_argument("--delete-branch", action="store_true", help="Deletar a branch associada.")
