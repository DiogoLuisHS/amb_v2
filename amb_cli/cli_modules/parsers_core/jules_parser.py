"""Módulo de registro do subparser 'jules' e seus comandos."""
from typing import Callable, Any


def register_jules_parser(subs: Any, c_fn: Callable, sc_fn: Callable, j_fn: Callable, sid_fn: Callable, cmd_jules: Callable) -> None:
    """Registra subparser 'jules' e seus subcomandos de integração."""
    p = c_fn("jules", "Comandos de integração com o Google Jules.", cmd_jules)
    js = p.add_subparsers(dest="jules_cmd", help="Subcomandos do Jules")
    j = sc_fn(js, "status", "Diagnóstico de conectividade, credenciais e sessões ativas do Jules.", ["check"])
    j.add_argument("--repo", "-r", help="Filtra o diagnóstico por repositório específico.")
    j_fn(j)
    j = sc_fn(js, "sources", "Lista fontes e repositórios conectados à conta Google Jules.", ["source"])
    j.add_argument("--filter", "-f", help="Filtro AIP-160 para consultar fontes específicas no Jules.")
    j_fn(j)
    j = sc_fn(js, "list", "Lista sessões recentes do repositório ou de toda a conta.")
    j.add_argument("--limit", "-n", type=int, default=10, help="Limite de sessões exibidas (padrão: 10).")
    j.add_argument("--all", "-a", action="store_true", help="Lista sessões de todos os repositórios (desativa filtro por repo atual).")
    j.add_argument("--repo", "-r", help="Filtra por repositório específico (ex: org/repo).")
    j.add_argument("--state", "-s", help="Filtra por estado (ex: AWAITING_USER_FEEDBACK, IN_PROGRESS, COMPLETED, FAILED).")
    j_fn(j)
    j = sc_fn(js, "get", "Exibe detalhes, PR ou faz streaming ao vivo da sessão.")
    sid_fn(j, "ID ou URL da sessão do Jules.")
    j.add_argument("--watch", "-w", action="store_true", help="Acompanha em tempo real as atividades e saídas da sessão.")
    j_fn(j)
    j = sc_fn(js, "watch", "Acompanha streaming contínuo de atividades e saídas da sessão em tempo real.", ["logs"])
    sid_fn(j, "ID ou URL da sessão do Jules.")
    j_fn(j)
    j = sc_fn(js, "create", "Cria uma nova sessão no Jules Cloud VM.")
    j.add_argument("prompt_pos", nargs="?", help="Instruções da tarefa ou caminho do arquivo .md (opcional se informado via -p).")
    j.add_argument("--prompt", "-p", required=False, help="Prompt ou caminho de arquivo com instruções da tarefa.")
    j.add_argument("--title", "-t", help="Título descritivo da sessão.")
    j.add_argument("--branch", "-b", help="Branch base inicial no repositório (padrão: auto-detecta a branch ativa do Git).")
    j.add_argument("--source", help="Fonte conectada no Jules (padrão: auto-detecta sources/github/owner/repo).")
    j.add_argument("--no-auto-pr", action="store_true", help="Desabilita a criação automática de Pull Request pelo Jules ao concluir.")
    j.add_argument("--require-approval", action="store_true", help="Exige aprovação explícita do plano antes de codificar.")
    j.add_argument("--no-repo", "--repoless", action="store_true", help="Cria sessão avulsa no Jules sem vincular repositório Git.")
    j.add_argument("--skip-branch-check", action="store_true", help="Ignora a validação preventiva de existência da branch na fonte do Jules.")
    j_fn(j)
    j = sc_fn(js, "rerun", "Recria e reinicia uma sessão anterior preservando prompt e contexto.", ["restart"])
    sid_fn(j, "ID ou URL da sessão original do Jules a ser reiniciada.")
    j.add_argument("--prompt", "-p", help="Sobrescreve o prompt original da sessão.")
    j.add_argument("--branch", "-b", help="Sobrescreve a branch original da sessão.")
    j_fn(j)
    j = sc_fn(js, "reply", "Responde uma dúvida com IA (ou envia mensagem direta se --message).", ["advisor", "ask"])
    sid_fn(j, "ID ou URL da sessão do Jules (opcional).", "ID ou URL da sessão (opcional; se omitido, lista todas as sessões pendentes).")
    j.add_argument("--message", "-m", help="Mensagem direta manual a ser enviada ao chat.")
    j.add_argument("--auto-approve", "-y", action="store_true", help="Envia resposta gerada pelo Gemini sem pedir confirmação.")
    j.add_argument("--force", "-f", action="store_true", help="Força envio ignorando guardrail de mensagens consecutivas do usuário.")
    j.add_argument("--chat", "-c", action="store_true", help="Inicia sessão de chat conversacional contínuo (REPL) com o agente Jules.")
    j = sc_fn(js, "approve", "Aprova o plano de execução de uma sessão.")
    sid_fn(j, "ID ou URL da sessão do Jules.")
    j.add_argument("--force", "-f", action="store_true", help="Força aprovação sem checar se o plano está em estado pendente.")
    j_fn(j)
    j = sc_fn(js, "extract", "Extrai e salva/aplica o código (patch) de uma sessão.")
    j.add_argument("session_id", help="ID ou URL da sessão do Jules.")
    j.add_argument("--dest", "-d", help="Caminho de destino para salvar o patch (Padrão: .amb/patches/session_<session_id>.patch).")
    j.add_argument("--apply", "-a", action="store_true", help="Aplica o patch extraído no workspace atual via git apply.")
    j.add_argument("--bash", action="store_true", help="Lista e exibe todos os comandos bash executados pelo Jules na VM com status e saídas.")
    j = sc_fn(js, "merge", "Detecta o PR da sessão, aprova, faz merge no GitHub e valida localmente.")
    sid_fn(j, "ID ou URL da sessão do Jules para detectar o PR.", "ID da sessão para detectar o PR (flag alternativa).")
    j.add_argument("--auto-latest", "-a", action="store_true", help="Detecta automaticamente o PR aberto mais recente.")
    j.add_argument("--branch", "-b", default="main", help="Branch de destino local após merge (padrão: main).")
    j = sc_fn(js, "clean", "Audita e remove na nuvem sessões do Jules já integradas.", ["cleanup"])
    j.add_argument("--force", "-f", action="store_true", help="Remove sem pedir confirmação.")
    j.add_argument("--failed", action="store_true", help="Remove todas as sessões que falharam (FAILED).")
    j.add_argument("--merged", action="store_true", help="Remove sessões cujos PRs já foram integrados ao Git.")
    j.add_argument("--all", action="store_true", help="Remove todas as sessões concluídas do escopo selecionado.")
    j.add_argument("--all-repos", action="store_true", help="Audita e remove sessões de todos os repositórios.")
    j.add_argument("--days", "-d", type=int, help="Filtra apenas sessões criadas há mais de N dias.")
    j.add_argument("--id", help="Remove uma sessão específica por ID.")
    j = sc_fn(js, "delete", "Deleta diretamente uma sessão específica no Jules.", ["del", "rm"])
    j.add_argument("session_id", help="ID ou URL da sessão do Jules.")
    j.add_argument("--force", "-f", action="store_true", help="Não pede confirmação interativa.")
    j = sc_fn(js, "env", "Diagnóstico de compatibilidade da stack local com a VM do Jules e script de snapshot.", ["environment"])
    j.add_argument("--dir", "-d", help="Diretório do projeto a ser analisado (padrão: diretório atual).")
    j_fn(j)
    j = sc_fn(js, "sync-issues", "Sincroniza arquivos de prompts com o GitHub Issues de forma idempotente.", ["issues", "sync"])
    j.add_argument("path", nargs="?", default=".amb/prompts", help="Diretório de prompts a sincronizar.")
    j.add_argument("--dry-run", action="store_true", help="Simula a sincronização sem criar issues.")
    j_fn(j)
